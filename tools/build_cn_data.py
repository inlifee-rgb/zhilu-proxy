#!/usr/bin/env python3
"""Build compact CN routing data for the Chrome extension.

Sources:
  * APNIC delegated-apnic-latest  (authoritative IP allocation table)
  * tools/cn-domains.txt          (curated Chinese domain suffix list)

Outputs:
  * tools/cn-ranges-v4.txt        (aggregated CN IPv4 CIDRs, audit copy)
  * tools/cn-ranges-v6.txt        (aggregated CN IPv6 CIDRs, audit copy)
  * data-cn.js                    (globals consumed by background.js)

Usage:
  python tools/build_cn_data.py [path/to/delegated-apnic-latest]
"""

from __future__ import annotations

import ipaddress
import math
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOOLS = ROOT / "tools"
DOMAIN_FILE = TOOLS / "cn-domains.txt"
APNIC_DEFAULT = TOOLS / "delegated-apnic-latest"


def load_apnic(path: Path) -> tuple[list[ipaddress.IPv4Network], list[ipaddress.IPv6Network]]:
    v4: list[ipaddress.IPv4Network] = []
    v6: list[ipaddress.IPv6Network] = []
    seen: set[str] = set()
    with path.open("r", encoding="utf-8", errors="replace") as fh:
        for line in fh:
            if not line.startswith("apnic|"):
                continue
            parts = line.strip().split("|")
            if len(parts) < 6 or parts[1] != "CN":
                continue
            kind, addr, size_raw = parts[2], parts[3], parts[4]
            key = f"{kind}:{addr}:{size_raw}"
            if key in seen:
                continue
            seen.add(key)
            try:
                if kind == "ipv4":
                    size = int(size_raw)
                    if size == 0 or size & (size - 1):  # must be power of two
                        continue
                    prefix = 32 - int(math.log2(size))
                    v4.append(ipaddress.IPv4Network(f"{addr}/{prefix}", strict=False))
                elif kind == "ipv6":
                    v6.append(ipaddress.IPv6Network(f"{addr}/{int(size_raw)}", strict=False))
            except (ValueError, ipaddress.AddressValueError):
                continue
    return v4, v6


def load_domains(path: Path) -> list[str]:
    out: list[str] = []
    seen: set[str] = set()
    with path.open("r", encoding="utf-8") as fh:
        for raw in fh:
            line = raw.strip().lower()
            if not line or line.startswith("#") or line.startswith("//"):
                continue
            line = line.lstrip(".")
            if line and line not in seen:
                seen.add(line)
                out.append(line)
    return sorted(out, key=lambda d: (-len(d), d))


def main() -> int:
    apnic = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else APNIC_DEFAULT
    if not apnic.exists():
        print(f"ERROR: APNIC source not found: {apnic}", file=sys.stderr)
        return 2

    v4_raw, v6_raw = load_apnic(apnic)
    v4 = [str(n) for n in ipaddress.collapse_addresses(v4_raw)]
    v6 = [str(n) for n in ipaddress.collapse_addresses(v6_raw)]
    domains = load_domains(DOMAIN_FILE)

    (TOOLS / "cn-ranges-v4.txt").write_text("\n".join(v4) + "\n", encoding="utf-8")
    (TOOLS / "cn-ranges-v6.txt").write_text("\n".join(v6) + "\n", encoding="utf-8")

    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    import json

    js = f"""/* AUTO-GENERATED by tools/build_cn_data.py — do not hand-edit.
 * Source: APNIC delegated-apnic-latest ({stamp}) + tools/cn-domains.txt
 * IPv4 CIDRs: {len(v4)} | IPv6 CIDRs: {len(v6)} | domains: {len(domains)}
 */
var CN_V4_CSV = {json.dumps(",".join(v4))};
var CN_V6_CSV = {json.dumps(",".join(v6))};
var CN_DOMAIN_CSV = {json.dumps(",".join(domains))};
var CN_DATA_META = {{
  generated: "{stamp}",
  source: "APNIC delegated-apnic-latest",
  v4: {len(v4)},
  v6: {len(v6)},
  domains: {len(domains)}
}};
"""
    (ROOT / "data-cn.js").write_text(js, encoding="utf-8")
    print(f"OK v4={len(v4)} v6={len(v6)} domains={len(domains)} -> data-cn.js")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
